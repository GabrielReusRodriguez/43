#include <unistd.h>

void	ft_putstr(char *str)
{
	while (*str != '\0')
	{
		write(1, str, 1);
		str++;
	}
}

void	ft_putline(char *str)
{
	ft_putstr(str);
	write(1, "\n", 1);
}
