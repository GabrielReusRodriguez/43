int ft_atoi(char *nbr)
{
	int	numero = 0;
	while (*nbr != '\0')
	{
		if (*nbr < '0' || *nbr > '9')
			return (numero);
		numero = numero * 10 + (*nbr - '0');
		nbr++;
	}
	return (numero);
}


